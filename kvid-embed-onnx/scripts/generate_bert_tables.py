"""Generates BertTables.kt: the per-code-point behavior of Hugging Face's BERT normalizer and
pre-tokenizer, so kvid's tokenizer matches the reference on every platform without relying on any
platform's Unicode tables.

Usage: python -I generate_bert_tables.py OUTPUT_KT
Requires: tokenizers (the version is recorded in the generated file).

For each code point the normalizer (clean_text, handle_chinese_chars, strip_accents, lowercase, the
configuration of bert-base-uncased and bge-small-en-v1.5) either removes it, surrounds it with spaces,
maps it to other text, or keeps it. The pre-tokenizer either splits on it and drops it (whitespace),
isolates it (punctuation), or keeps it inside words. Normalizing a string code point by code point is
equivalent to normalizing it whole, except for canonical reordering of combining marks that accent
stripping does not remove; that difference is accepted.
"""
import sys
import tokenizers
from tokenizers.normalizers import BertNormalizer
from tokenizers.pre_tokenizers import BertPreTokenizer

CHUNK = 20000


def ranges(points):
    out, start, prev = [], None, None
    for cp in points:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev)); start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def encode_ranges(rs):
    return ",".join(f"{a:x}" if a == b else f"{a:x}-{b:x}" for a, b in rs)


def main(output):
    normalizer = BertNormalizer(clean_text=True, handle_chinese_chars=True, strip_accents=None, lowercase=True)
    pre = BertPreTokenizer()
    removed, padded, mapped, punct, space = [], [], [], [], []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        out = normalizer.normalize_str(c)
        if out == "":
            removed.append(cp)
        elif out == f" {c} ":
            padded.append(cp)
        elif out != c:
            mapped.append((cp, out))
        pieces = [t for t, _ in pre.pre_tokenize_str("a" + c + "b")]
        if pieces == ["a", "b"]:
            space.append(cp)
        elif pieces == ["a", c, "b"]:
            punct.append(cp)
        elif pieces != ["a" + c + "b"]:
            raise SystemExit(f"unexpected pre-tokenization of U+{cp:04X}: {pieces}")

    mapping = ";".join(f"{cp:x}=" + ".".join(f"{ord(ch):x}" for ch in out) for cp, out in mapped)
    sections = {
        "REMOVED": encode_ranges(ranges(removed)),
        "PADDED": encode_ranges(ranges(padded)),
        "PUNCTUATION": encode_ranges(ranges(punct)),
        "WHITESPACE": encode_ranges(ranges(space)),
        "MAPPED": mapping,
    }

    def chunks(text):
        return [text[i:i + CHUNK] for i in range(0, len(text), CHUNK)] or [""]

    lines = [
        "// Generated by kvid-embed-onnx/scripts/generate_bert_tables.py; do not edit.",
        f"// Source: Hugging Face tokenizers {tokenizers.__version__}, BertNormalizer(clean_text, handle_chinese_chars,",
        "// strip_accents, lowercase) and BertPreTokenizer, evaluated for every Unicode scalar value.",
        f"// Counts: {len(removed)} removed, {len(padded)} padded, {len(mapped)} mapped, {len(punct)} punctuation, {len(space)} whitespace.",
        "package com.kvid.embed",
        "",
        "internal object BertTables {",
        f"    const val SOURCE = \"tokenizers {tokenizers.__version__}\"",
    ]
    for name, text in sections.items():
        parts = ",\n".join(f"        \"{part}\"" for part in chunks(text))
        lines.append(f"    val {name}: Array<String> = arrayOf(\n{parts}\n    )")
    lines.append("}")
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"tokenizers {tokenizers.__version__}: {len(removed)} removed, {len(padded)} padded, {len(mapped)} mapped, "
          f"{len(punct)} punctuation, {len(space)} whitespace -> {output}")


if __name__ == "__main__":
    main(sys.argv[1])
